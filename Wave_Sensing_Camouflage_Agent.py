import random
import matplotlib.pyplot as plt
import numpy as np

np.random.seed(42)
random.seed(42)


class WaveSensingCamouflageAgent:
    def __init__(self):
        self.energy = 100.0
        self.short_term_memory = list()
        self.long_term_memory = dict()
        self.curiosity_score = 0.0
        self.stealth_broken_count = 0
        self.importance_threshold = 5.0
        self.stealth_movement_limit = 0.25
    def sense_environment(self, entity_wave_signature, is_background_noise):
        if is_background_noise:
            self.energy -= 0.05
            return None
        else:
            self.energy -= 0.40
            return entity_wave_signature

    def maintain_cognitive_camouflage(self, agent_drift_speed, wave_pulse_intensity):
         if self.stealth_movement_limit >= agent_drift_speed and 0.5 >= wave_pulse_intensity:
            return True
         else:
            self.stealth_broken_count = self.stealth_broken_count + 1
            return False

    def process_wave_data(self, entity_name, wave_signature, step):
        if entity_name in self.long_term_memory:
            expected_wave = self.long_term_memory.get(entity_name)
            importance = abs(expected_wave - wave_signature) * 0.5
            self.short_term_memory.append((step, entity_name, importance))
            self.curiosity_score = self.curiosity_score + 0.5
            return "KNOWN_MEMOIZED", importance
        else:
            importance = abs(0.0 - wave_signature) * 3.0
            if importance >= self.importance_threshold:
                self.long_term_memory.update({entity_name: wave_signature})
                self.curiosity_score = self.curiosity_score + 15.0
                return "NOVEL_SPECIES_LOCKED", importance
            else:
                self.short_term_memory.append((step, entity_name, importance))
                return "LOW_IMPORTANCE_STM", importance


    def offline_sleep_pruning(self):
        pruned_count = len(self.short_term_memory)
        self.short_term_memory.clear()
        return pruned_count


def run_deep_sea_simulation(total_steps=100):
    agent = WaveSensingCamouflageAgent()

    event_0 = ("Ocean_Current_Noise", 0.1, True)
    event_1 = ("Deep_Jellyfish", 2.5, False)
    event_2 = ("Abyssal_Shrimp", 3.2, False)
    event_3 = ("Unknown_Bioluminescent_Cephalopod", 8.5, False)
    event_4 = ("Unknown_Trench_Leviathan", 9.8, False)
    event_5 = ("Unknown_Magnetic_Ray", 7.4, False)

    known_creatures = (event_1, event_2)
    novel_creatures = (event_3, event_4, event_5)
    discovery_steps = (15, 45, 78)

    steps_log = list()
    curiosity_log = list()
    ltm_nodes_log = list()
    energy_log = list()
    novelty_spikes = list()

    for step in range(total_steps):
        spike_val = 0.0

        # 1. Event Selection
        if step in discovery_steps:
            novel_idx = discovery_steps.index(step)
            event = novel_creatures[novel_idx]
        elif 0.70 >= random.random():
            event = event_0
        else:
            event = random.choice(known_creatures)

        entity_name, wave_sig, is_noise = event

        # 2. Sense & Camouflage
        detected_wave = agent.sense_environment(wave_sig, is_noise)
        drift_speed = random.uniform(0.05, 0.22)
        pulse_power = 0.0 if is_noise else 0.4
        is_invisible = agent.maintain_cognitive_camouflage(drift_speed, pulse_power)

        # 3. Process Wave Data & Update Curiosity
        if detected_wave is not None and is_invisible:
            status, importance = agent.process_wave_data(entity_name, detected_wave, step)
            if status == "NOVEL_SPECIES_LOCKED":
                spike_val = importance
                print(f"Step {step:02d} | DISCOVERY: {entity_name} | Spike: +{importance:.2f}")

        # 4. Offline Sleep Pruning every 20 steps
        if step > 0 and step % 20 == 0:
            pruned = agent.offline_sleep_pruning()
            print(f"Step {step:02d} | Offline Sleep Cycle: Pruned {pruned} trivial wave events.")

        # Record metrics for plotting
        steps_log.append(step)
        curiosity_log.append(agent.curiosity_score)
        ltm_nodes_log.append(len(agent.long_term_memory))
        energy_log.append(agent.energy)
        novelty_spikes.append(spike_val)


    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 7), sharex=True)

    ax1.plot(steps_log, curiosity_log, color="#1f77b4", linewidth=2.5)
    ax1_twin = ax1.twinx()
    ax1_twin.plot(steps_log, energy_log, color="#ff7f0e", linestyle="--", linewidth=2)
    ax1.set_title("Figure 1A: Autonomous Discovery Score & Ultra-Low Energy Conservation", fontsize=11, fontweight="bold")
    ax1.set_ylabel("Curiosity Reward Score", color="#1f77b4", fontweight="bold")
    ax1_twin.set_ylabel("Battery Energy (%)", color="#ff7f0e", fontweight="bold")
    ax1.grid(True, linestyle=":", alpha=0.6)

    ax2.bar(steps_log, novelty_spikes, color="#d62728", width=1.2)
    ax2_twin = ax2.twinx()
    ax2_twin.plot(steps_log, ltm_nodes_log, color="#2ca02c", linewidth=2.5)
    ax2.set_title("Figure 1B: Wave-Based Novelty Detection & Memory Bloat Prevention", fontsize=11, fontweight="bold")
    ax2.set_xlabel("Deep-Sea Mission Time (Steps)", fontweight="bold")
    ax2.set_ylabel("Importance Gate Spike", color="#d62728", fontweight="bold")
    ax2_twin.set_ylabel("Consolidated Memory Nodes", color="#2ca02c", fontweight="bold")
    ax2.grid(True, linestyle=":", alpha=0.6)

    plt.tight_layout()
    plt.savefig("Wave_Sensing_Simulation_Results.png", dpi=300)
    plt.show()


if __name__ == "__main__":
    run_deep_sea_simulation(total_steps=100)

